// ── Combined all wards ─────────────────────────────────────────────────────────
export const ALL_WARDS: Ward[] = [
  ...BENGALURU_WARDS,
  ...MYSURU_WARDS,
  ...MANDYA_WARDS,
];

// ── Find nearest ward from GPS coordinates ─────────────────────────────────────
export function findNearestWard(lat: number, lng: number): Ward {
  let nearest = ALL_WARDS[0];
  let minDist = Infinity;

  for (const ward of ALL_WARDS) {
    const d = Math.sqrt((lat - ward.lat) ** 2 + (lng - ward.lng) ** 2);
    if (d < minDist) {
      minDist = d;
      nearest = ward;
    }
  }

  return nearest;
}

// ── Detect which city a GPS point belongs to ───────────────────────────────────
export function detectCity(lat: number, lng: number): 'Bengaluru' | 'Mysuru' | 'Mandya' {
  const ward = findNearestWard(lat, lng);
  return ward.city;
}

// Deterministic risk assignment based on ward coordinates
// (mirrors backend mock logic for visual consistency)
export function getWardRisk(ward: Ward) {
  const seed = ward.lat * 1000 + ward.lng;
  const h = Math.sin(seed) * 43758.5453;
  const score = ((h - Math.floor(h)) * 100);
  // High-density central areas tend to be hotter — adjusted per city center
  const cityCenters = {
    Bengaluru: { lat: 12.97, lng: 77.59 },
    Mysuru: { lat: 12.31, lng: 76.65 },
    Mandya: { lat: 12.52, lng: 76.90 },
  };
  const center = cityCenters[ward.city] || cityCenters.Bengaluru;
  const centralPenalty = (Math.abs(ward.lat - center.lat) + Math.abs(ward.lng - center.lng)) < 0.05 ? 15 : 0;
  const finalScore = Math.min(100, score + centralPenalty);
  let level: string;
  if (finalScore > 75) level = 'critical';
  else if (finalScore > 55) level = 'high';
  else if (finalScore > 35) level = 'moderate';
  else level = 'low';
  return { score: Math.round(finalScore), level, ndvi: +(0.1 + (1 - finalScore/100) * 0.4).toFixed(3), lst: +(28 + (finalScore/100) * 12).toFixed(1) };
}
